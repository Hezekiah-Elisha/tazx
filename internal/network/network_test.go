func TestParseProcNetRoute(t *testing.T) {
	sample := `Iface	Destination	Gateway 	Flags	RefCnt	Use	Metric	Mask		MTU	Window	IRTT
eth0	00000000	0101A8C0	0003	0	0	100	00000000	0	0	0
eth0	0001A8C0	00000000	0001	0	0	100	00FFFFFF	0	0	0
`
	gw, err := ParseProcNetRoute(strings.NewReader(sample))
	if err != nil {
		t.Fatalf("ParseProcNetRoute failed: %v", err)
	}
	if gw == nil {
		t.Fatal("expected non-nil default gateway")
	}
	// 0x0101A8C0 in little-endian = 192.168.1.1
	if gw.Interface != "eth0" || gw.GatewayIP != "192.168.1.1" {
		t.Errorf("got %+v, want eth0 / 192.168.1.1", gw)
	}
}

func TestParseResolvConf(t *testing.T) {
	sample := `
# Generated by NetworkManager
search corp.local example.com
nameserver 1.1.1.1
nameserver 8.8.8.8 # inline comment
nameserver 1.1.1.1
`
	cfg, err := ParseResolvConf(strings.NewReader(sample))
	if err != nil {
		t.Fatalf("ParseResolvConf failed: %v", err)
	}
	if len(cfg.Nameservers) != 2 || cfg.Nameservers[0] != "1.1.1.1" || cfg.Nameservers[1] != "8.8.8.8" {
		t.Errorf("unexpected nameservers: %+v", cfg.Nameservers)
	}
	if len(cfg.SearchDomains) != 2 {
		t.Errorf("unexpected search domains: %+v", cfg.SearchDomains)
	}
}

func TestValidateCheckHost(t *testing.T) {
	if h, err := ValidateCheckHost(""); err != nil || h != "example.com" {
		t.Errorf("empty host should default to example.com, got %q / %v", h, err)
	}
	if _, err := ValidateCheckHost("bad;host"); err == nil {
		t.Error("expected injection host to fail validation")
	}
}

func TestGetNetworkOverview(t *testing.T) {
	overview, err := GetNetworkOverview(context.Background(), false, "")
	if err != nil {
		t.Fatalf("GetNetworkOverview failed: %v", err)
	}
	if len(overview.Interfaces) == 0 {
		t.Fatal("expected at least loopback interface")
	}
}
